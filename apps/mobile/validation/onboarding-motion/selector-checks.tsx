import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { NavigationContext } from '@react-navigation/native';
import { SafeAreaProvider } from 'react-native-safe-area-context';
import assert from 'node:assert/strict';
import PatientSelector from '../../src/components/PatientSelector';
import { fixture } from './selector-mocks';

const root = createRoot(document.getElementById('app')!);
const results: string[] = [];
const navigation = { isFocused: () => true, addListener: () => () => {} } as any;
const render = async () => act(async () => root.render(<SafeAreaProvider initialMetrics={{ frame: { x: 0, y: 0, width: 430, height: 932 }, insets: { top: 0, bottom: 0, left: 0, right: 0 } }}><NavigationContext.Provider value={navigation}><PatientSelector /></NavigationContext.Provider></SafeAreaProvider>));
const button = (label: string) => document.querySelector(`[aria-label="${label}"]`) as HTMLElement;
const flush = async () => act(async () => { await new Promise(resolve => setTimeout(resolve, 20)); });
try {
  fixture.admin = false; await render();
  assert.equal(document.querySelector('[data-testid="profile-patient-dropdown"]'), null);
  assert.equal(fixture.requests.length, 0);
  results.push('ordinary patients have no selector or directory request');
  fixture.admin = true; await render();
  const trigger = document.querySelector('[data-testid="profile-patient-dropdown"]') as HTMLElement;
  assert.ok(trigger); assert.equal(fixture.requests.length, 0);
  await act(async () => trigger.click()); await flush();
  assert.ok(document.querySelector('[data-testid="profile-patient-menu"]'));
  assert.deepEqual(fixture.requests, ['/patient/demo/patients']);
  assert.ok(button('Example Alpha, MRN-A')); assert.ok(button('Example Beta, MRN-B'));
  results.push('administrator dropdown loads the directory only when opened');
  await act(async () => button('Example Beta, MRN-B').click()); await flush();
  assert.deepEqual(fixture.selected, ['patient-b']);
  assert.equal(document.querySelector('[data-testid="profile-patient-menu"]'), null);
  results.push('selecting a patient changes the subject and closes the dropdown');
  await act(async () => trigger.click()); await flush();
  assert.equal(button('Example Beta, MRN-B').getAttribute('aria-checked'), 'true');
  await act(async () => button('Close patient selection').click()); await flush();
  assert.equal(document.querySelector('[data-testid="profile-patient-menu"]'), null);
  assert.deepEqual(fixture.selected, ['patient-b']);
  results.push('current selection is marked and dismissing never changes it');
  await act(async () => root.unmount());
  console.log(JSON.stringify({ passed: results.length, results }));
  (globalThis as any).__onboardingMotionResults = results;
} catch (error) { await act(async () => root.unmount()); throw error; }
