import Svg, { Path, Circle, Ellipse, type SvgProps } from 'react-native-svg';
import { solarData, solarNames, type SolarWeight } from '../../../shared/solar-icons/data';
export interface SolarIconProps extends SvgProps { size?: number | string; weight?: SolarWeight; }
function createSolarIcon(name: string) {
  const Icon = ({ size = 24, color = 'currentColor', strokeWidth = 1.5, weight = 'Linear', ...props }: SolarIconProps) => {
    const slug = solarNames[name];
    const nodes = solarData[`${weight}:${slug}`] || solarData[`Linear:${slug}`];
    return <Svg width={size} height={size} viewBox="0 0 24 24" fill="none" color={color} accessible={false} {...props}>
      {nodes.map((node, index) => {
        const attrs = { ...node.attrs, ...(node.attrs.stroke ? { strokeWidth } : {}) };
        return node.tag === 'path' ? <Path key={index} {...attrs} /> : node.tag === 'circle' ? <Circle key={index} {...attrs} /> : <Ellipse key={index} {...attrs} />;
      })}
    </Svg>;
  };
  Icon.displayName = `Solar${name}`;
  return Icon;
}
