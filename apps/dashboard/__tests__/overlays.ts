import assert from 'node:assert/strict';
import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
import { createRequire } from 'node:module';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { tmpdir } from 'node:os';
import { build } from 'esbuild';

const { JSDOM } = await import(process.env.MEDCORE_DOM_MODULE || '/private/tmp/medcore-visual-tools/node_modules/jsdom/lib/api.js');
const dom = new JSDOM('<header style="position:sticky;z-index:30">Header</header><div id="root" style="transform:scale(.95);overflow:hidden"></div>');
Object.defineProperty(globalThis, 'document', { value: dom.window.document, configurable: true });
Object.defineProperty(globalThis, 'window', { value: dom.window, configurable: true });
Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true });
const css = await readFile('apps/dashboard/src/index.css', 'utf8');
const style = document.createElement('style');style.textContent = css.slice(css.indexOf('/* Full viewport overlays:'));document.head.append(style);
const require = createRequire(resolve('package.json'));
const directory = await mkdtemp(join(tmpdir(), 'medcore-overlay-dom-'));
const compiled = join(directory, 'overlay.cjs');
await build({entryPoints:['apps/dashboard/src/components/common/ViewportOverlay.tsx'],bundle:true,format:'cjs',platform:'node',outfile:compiled,plugins:[{name:'shared-react',setup(b){b.onResolve({filter:/^react(?:\/.+)?$|^react-dom(?:\/.+)?$/},args=>({path:require.resolve(args.path),external:true}));}}]});
const { ViewportOverlay } = require(compiled);
const root=createRoot(document.getElementById('root')!);
let outerDismiss=0,innerDismiss=0;
const scene=()=>React.createElement(ViewportOverlay,{motion:'right',className:'overflow-hidden flex justify-end',onDismiss:()=>outerDismiss++},
  React.createElement('section',{'data-panel':'outer'},'Drawer',
    React.createElement(ViewportOverlay,{layer:'nested',onDismiss:()=>innerDismiss++},React.createElement('article',{'data-panel':'inner'},'Nested checkout'))));
const click=(element:Element)=>act(async()=>{element.dispatchEvent(new dom.window.MouseEvent('click',{bubbles:true}));});
let passed=0;const pass=(name:string)=>{passed++;console.log(`[PASS] ${name}`);};
try {
  await act(async()=>{root.render(scene());});
  const overlays=[...document.querySelectorAll<HTMLElement>('[data-overlay-root]')];assert.equal(overlays.length,2);
  assert.ok(overlays.every(o=>o.parentElement===document.body));
  assert.ok(overlays.every(o=>dom.window.getComputedStyle(o).position==='fixed'&&['0','0px'].includes(dom.window.getComputedStyle(o).inset)));
  assert.ok(overlays.every(o=>Number(o.style.zIndex)>30));
  pass('Body-portaled overlays escape transformed/clipped pages and cover the header');
  const outer=document.querySelector<HTMLElement>('[data-overlay-layer="modal"]')!;
  const inner=document.querySelector<HTMLElement>('[data-overlay-layer="nested"]')!;
  assert.ok(Number(inner.style.zIndex)>Number(outer.style.zIndex));
  const backdrop=outer.querySelector<HTMLElement>('[data-overlay-backdrop]')!;
  const stage=outer.querySelector<HTMLElement>('[data-overlay-stage]')!;
  assert.equal(backdrop.parentElement,stage.parentElement);assert.equal(stage.dataset.overlayMotion,'right');
  assert.equal(dom.window.getComputedStyle(outer).overflow,'hidden');
  assert.equal(dom.window.getComputedStyle(stage).overflowX,'hidden');
  assert.equal(dom.window.getComputedStyle(stage).overflowY,'hidden');
  assert.equal(dom.window.getComputedStyle(inner.querySelector('[data-overlay-stage]')!).overflowY,'auto');
  assert.ok(['','none'].includes(dom.window.getComputedStyle(backdrop).transform));
  assert.ok(style.textContent!.includes('.viewport-overlay-stage[data-overlay-motion="right"] > *'));
  assert.ok(style.textContent!.includes('prefers-reduced-motion: reduce'));
  assert.ok(style.textContent!.includes('@media print { .viewport-overlay { display: none !important; } }'));
  pass('Stationary sibling scrim, drawer-only transform, reduced motion and print exclusion');
  await click(document.querySelector('[data-panel="inner"]')!);assert.equal(innerDismiss,0);assert.equal(outerDismiss,0);
  await click(inner.querySelector('[data-overlay-backdrop]')!);assert.equal(innerDismiss,1);assert.equal(outerDismiss,0);
  await click(backdrop);assert.equal(outerDismiss,1);
  pass('Nested dialog clicks/backdrop never dismiss the underlying dialog');
  await act(async()=>{root.render(React.createElement(ViewportOverlay,{layer:'processing'},React.createElement('section',null,'Busy')));});
  const busy=document.querySelector<HTMLElement>('[data-overlay-layer="processing"]')!;
  await click(busy.querySelector('[data-overlay-backdrop]')!);assert.equal(outerDismiss,1);assert.equal(innerDismiss,1);
  pass('Busy processing backdrops remain nondismissable');
  await act(async()=>{root.render(React.createElement(ViewportOverlay,{layer:'confirmation'},React.createElement('section',null,'Confirm')));});
  assert.equal(document.querySelector<HTMLElement>('[data-overlay-root]')!.style.zIndex,'9999');
  pass('Confirmation stays above other overlays');
  await act(async()=>{root.unmount();});assert.equal(document.querySelector('[data-overlay-root]'),null);
  pass('Unmount removes portal surfaces');
  console.log(`DASHBOARD_OVERLAY_CHECKS_DONE passed=${passed}`);
} finally {dom.window.close();await rm(directory,{recursive:true,force:true});}
